// Writes one page per space so a shared link shows that space's preview (WhatsApp, Instagram, X and others read the
// Open Graph tags in the HTML and never run JavaScript). Run after adding or changing a space:
//   node tools/build-pages.mjs
// For each entry in rooms/spaces.json it writes pages/<id>.html (space.html with that space's title and preview tags)
// and rooms/<id>/og.jpg (1200 x 630, cut from the space's cover). vercel.json and serve.js serve /<id> from pages/<id>.html.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url'; import { createRequire } from 'module';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharp = createRequire(path.join(ROOT, '..', 'House Walkthrough', 'package.json'))('sharp');
const SITE = 'https://playablespaces.vercel.app';
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const spaces = JSON.parse(fs.readFileSync(path.join(ROOT, 'rooms', 'spaces.json'), 'utf8'));
const app = fs.readFileSync(path.join(ROOT, 'space.html'), 'utf8');
fs.mkdirSync(path.join(ROOT, 'pages'), { recursive: true });

for (const s of spaces) {
  const og = `rooms/${s.id}/og.jpg`;
  // a wide render made for sharing (share.image, 1200 x 630) beats a crop of the gallery cover, which clips the room
  await sharp(path.join(ROOT, s.share?.image || s.cover)).resize(1200, 630, { fit: 'cover', position: 'centre' }).jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(ROOT, og));
  const title = s.share?.title || `${s.store}: a home you can play with`;
  const desc = s.share?.description || s.facts.join('. ') + '.';
  const url = `${SITE}/${s.id}`;
  const tags = [
    `<title>${esc(title)} · Playable Spaces</title>`,
    `<meta name="description" content="${esc(desc)}">`,
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="Playable Spaces">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(desc)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${SITE}/${og}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(`${s.store} ${s.title.toLowerCase()}, a 3D home on a plinth`)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:image" content="${SITE}/${og}">`,
  ].join('\n');
  if (!app.includes('<title>Playable Spaces</title>')) throw new Error('space.html has no plain <title> to replace');
  const page = `<!-- generated by tools/build-pages.mjs from space.html for ${s.id}; edit space.html and rebuild -->\n` + app.replace('<title>Playable Spaces</title>', tags);
  fs.writeFileSync(path.join(ROOT, 'pages', `${s.id}.html`), page);
  const kb = Math.round(fs.statSync(path.join(ROOT, og)).size / 1024);
  console.log(`${s.id}: pages/${s.id}.html, ${og} (${kb} KB)`);
}
